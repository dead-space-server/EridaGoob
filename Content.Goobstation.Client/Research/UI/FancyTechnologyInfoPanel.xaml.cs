using Content.Client.Lathe;
using Content.Goobstation.Common.Research;
using Content.Shared.Research.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics; // Erida edit
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Goobstation.Client.Research.UI;

[GenerateTypedNameReferences]
public sealed partial class FancyTechnologyInfoPanel : Control
{
    [Dependency] private IEntityManager _ent = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    public TechnologyPrototype Prototype;
    public Action<TechnologyPrototype>? BuyAction;
    public Action<TechnologyPrototype>? SelectPrerequisiteAction; // Erida edit

    // Erida start
    public FancyTechnologyInfoPanel(
        TechnologyPrototype proto,
        bool hasAccess,
        ResearchAvailability availability,
        SpriteSystem sprite,
        IReadOnlyDictionary<string, ResearchAvailability> allTechs)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var lathe = _ent.System<LatheSystem>();
        Prototype = proto;

        var discipline = _proto.Index(proto.Discipline);
        TechnologyNameLabel.Text = Loc.GetString(proto.Name);
        TechnologyNameLabel.ToolTip = TechnologyNameLabel.Text;
        DisciplineTexture.Texture = sprite.Frame0(discipline.Icon);
        DisciplineLabel.Text = Loc.GetString(discipline.Name);
        TierLabel.Text = $"· {Loc.GetString("research-console-metric-tier", ("tier", proto.Tier))}";
        TechnologyTexture.Texture = sprite.Frame0(proto.Icon);

        var (accentColor, _, _, _) = ResearchUiPalette.GetAvailabilityColors(availability);

        if (StatusAccentPanel.PanelOverride is StyleBoxFlat statusAccent)
            statusAccent.BorderColor = accentColor;

        if (CostAccentPanel.PanelOverride is StyleBoxFlat costAccent)
            costAccent.BorderColor = availability == ResearchAvailability.Available
                ? ResearchUiPalette.HeaderAccent
                : accentColor;

        TechnologyCostLabel.Text = Loc.GetString("research-console-tech-cost-label", ("cost", proto.Cost));
        TechnologyCostLabel.FontColorOverride = ResearchUiPalette.TextPrimary;

        TechnologyStatusLabel.Text = availability switch
        {
            ResearchAvailability.Researched => Loc.GetString("research-console-status-researched"),
            ResearchAvailability.Available => Loc.GetString("research-console-status-available"),
            ResearchAvailability.PrereqsMet => Loc.GetString("research-console-status-prereqs-met"),
            _ => Loc.GetString("research-console-status-unavailable")
        };
        TechnologyStatusLabel.FontColorOverride = accentColor;

        InitializePrerequisites(proto, sprite, allTechs);
        InitializeRecipeUnlocks(proto, lathe, sprite);

        ResearchButton.ToolTip = !hasAccess
            ? Loc.GetString("research-console-no-access-popup")
            : null;

        ResearchButton.Text = availability == ResearchAvailability.Researched
            ? Loc.GetString("research-console-menu-server-researched-button")
            : Loc.GetString("research-console-menu-server-research-button");

        ResearchButton.Disabled = !hasAccess || availability != ResearchAvailability.Available;
        ResearchButton.OnPressed += Bought;
    }

    private void InitializePrerequisites(
        TechnologyPrototype proto,
        SpriteSystem sprite,
        IReadOnlyDictionary<string, ResearchAvailability> allTechs)
    {
        var hasPrereqs = proto.TechnologyPrerequisites.Count > 0;
        NoPrereqLabel.Visible = !hasPrereqs;
        PrereqsScroll.Visible = hasPrereqs;

        RequiredTechContainer.RemoveAllChildren();
        foreach (var techId in proto.TechnologyPrerequisites)
        {
            var tech = _proto.Index(techId);
            var prereqAvailability = allTechs.TryGetValue(techId, out var av)
                ? av
                : ResearchAvailability.Unavailable;
            var (accent, _, _, _) = ResearchUiPalette.GetAvailabilityColors(prereqAvailability);

            var card = new PanelContainer
            {
                HorizontalExpand = true,
                PanelOverride = new StyleBoxFlat
                {
                    BorderThickness = new Thickness(3, 0, 0, 0),
                    BorderColor = accent
                }
            };

            var inner = new PanelContainer
            {
                Margin = new Thickness(2, 0, 0, 0),
                HorizontalExpand = true,
                PanelOverride = new StyleBoxFlat
                {
                    BackgroundColor = ResearchUiPalette.PanelBackground,
                    BorderColor = ResearchUiPalette.CardBorder,
                    BorderThickness = new Thickness(1)
                }
            };

            var btn = new Button
            {
                ModulateSelfOverride = Color.Transparent,
                HorizontalExpand = true,
                VerticalExpand = true
            };
            btn.OnPressed += _ => SelectPrerequisiteAction?.Invoke(tech);

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new Thickness(6, 4),
                SeparationOverride = 8,
                VerticalAlignment = VAlignment.Center,
                MouseFilter = MouseFilterMode.Ignore
            };

            row.AddChild(new TextureRect
            {
                Texture = sprite.Frame0(tech.Icon),
                SetSize = new System.Numerics.Vector2(24, 24),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                VerticalAlignment = VAlignment.Center,
                MouseFilter = MouseFilterMode.Ignore
            });

            var textCol = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                MouseFilter = MouseFilterMode.Ignore
            };

            textCol.AddChild(new Label
            {
                Text = Loc.GetString(tech.Name),
                ClipText = true,
                FontColorOverride = ResearchUiPalette.TextPrimary,
                MouseFilter = MouseFilterMode.Ignore
            });

            var disc = _proto.Index(tech.Discipline);
            textCol.AddChild(new Label
            {
                Text = $"{Loc.GetString(disc.Name)} · T{tech.Tier}",
                StyleClasses = { "LabelSubText" },
                FontColorOverride = ResearchUiPalette.TextSecondary,
                MouseFilter = MouseFilterMode.Ignore
            });

            row.AddChild(textCol);
            inner.AddChild(btn);
            inner.AddChild(row);
            card.AddChild(inner);
            RequiredTechContainer.AddChild(card);
        }
    }

    private void InitializeRecipeUnlocks(TechnologyPrototype proto, LatheSystem lathe, SpriteSystem sprite)
    {
        UnlocksContainer.RemoveAllChildren();
        NoUnlocksLabel.Visible = proto.RecipeUnlocks.Count == 0;

        foreach (var recipeId in proto.RecipeUnlocks)
        {
            var recipe = _proto.Index(recipeId);
            UnlocksContainer.AddChild(new MiniRecipeCardControl(proto, recipe, _proto, sprite, lathe));
        }
    }
    // Erida end

    protected override void ExitedTree()
    {
        base.ExitedTree();

        ResearchButton.OnPressed -= Bought;
    }

    private void Bought(BaseButton.ButtonEventArgs args)
    {
        BuyAction?.Invoke(Prototype);
    }
}
