namespace Content.Goobstation.Client.Research.UI;

[GenerateTypedNameReferences]
public sealed partial class FancyResearchConsoleItem : LayoutContainer
{
    // Erida start
    public const float BaseWidth = 228f;
    public const float BaseHeight = 48f;

    private static readonly Dictionary<int, Stylesheet> TitleStylesheetCache = new();

    [Dependency] private IResourceCache _resCache = default!;

    public TechnologyPrototype Prototype;
    public Action<TechnologyPrototype, ResearchAvailability>? SelectAction;
    public ResearchAvailability Availability;

    private readonly Color _accentColor;
    private readonly Color _bgColor;
    private readonly Color _hoverColor;
    private readonly Color _borderColor;
    private bool _selected;
    private bool _searchMatched;
    private bool _searchDimmed;

    public bool IsHovered => Button.IsHovered;
    public bool IsSelected => _selected;
    public bool IsSearchDimmed => _searchDimmed;

    public FancyResearchConsoleItem(TechnologyPrototype proto, SpriteSystem sprite, ResearchAvailability availability)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Availability = availability;
        Prototype = proto;

        ResearchDisplay.Texture = sprite.Frame0(proto.Icon);
        var name = Loc.GetString(proto.Name);
        CostLabel.Text = Loc.GetString("research-console-tech-cost-label", ("cost", proto.Cost));
        TierLabel.Text = $"· T{proto.Tier}";

        Button.ToolTip = name;
        Button.OnPressed += Selected;
        Button.OnDrawModeChanged += UpdateColor;

        (_accentColor, _bgColor, _hoverColor, _borderColor) = ResearchUiPalette.GetAvailabilityColors(availability);

        var isDimmed = availability == ResearchAvailability.Unavailable;
        var titleColor = isDimmed ? ResearchUiPalette.TextSecondary : ResearchUiPalette.TextPrimary;
        var msg = new FormattedMessage();
        msg.PushColor(titleColor);
        msg.AddText(name);
        msg.Pop();
        TechNameLabel.SetMessage(msg);

        CostLabel.FontColorOverride = isDimmed ? ResearchUiPalette.TextDimmed : ResearchUiPalette.TextSecondary;
        TierLabel.FontColorOverride = ResearchUiPalette.TextDimmed;
        ResearchDisplay.ModulateSelfOverride = isDimmed ? Color.White.WithAlpha(0.65f) : Color.White;

        UpdateColor();
    }

    public void SetSelected(bool selected)
    {
        _selected = selected;
        UpdateColor();
    }

    public void SetSearchState(bool isDirectMatch, bool isInChain, bool searchActive)
    {
        if (!searchActive)
        {
            _searchMatched = false;
            _searchDimmed = false;
            Modulate = Color.White;
        }
        else if (isDirectMatch)
        {
            _searchMatched = true;
            _searchDimmed = false;
            Modulate = Color.White;
        }
        else if (isInChain)
        {
            _searchMatched = false;
            _searchDimmed = false;
            Modulate = Color.White;
        }
        else
        {
            _searchMatched = false;
            _searchDimmed = true;
            Modulate = Color.White.WithAlpha(0.22f);
        }

        UpdateColor();
    }

    private void UpdateColor()
    {
        var accentBox = (StyleBoxFlat) AccentPanel.PanelOverride!;
        accentBox.BorderColor = _accentColor;

        var cardBox = (StyleBoxFlat) CardPanel.PanelOverride!;
        cardBox.BackgroundColor = Button.IsHovered ? _hoverColor : _bgColor;
        cardBox.BorderColor = _selected
            ? ResearchUiPalette.SelectedBorder
            : (_searchMatched ? ResearchUiPalette.SearchMatchBorder : _borderColor);
        cardBox.BorderThickness = _selected || _searchMatched ? new Thickness(2) : new Thickness(1);
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        Button.OnPressed -= Selected;
        Button.OnDrawModeChanged -= UpdateColor;
    }

    private void Selected(BaseButton.ButtonEventArgs args)
    {
        SelectAction?.Invoke(Prototype, Availability);
    }

    public void SetScale(float scale)
    {
        var width = BaseWidth * scale;
        CardBox.MinWidth = width;
        CardBox.MaxWidth = width;
        CardBox.MinHeight = BaseHeight * scale;

        var iconSize = Math.Clamp(28f * scale, 18f, 36f);
        ResearchDisplay.SetSize = new Vector2(iconSize, iconSize);

        var titleFontSize = Math.Clamp((int) MathF.Round(10f * scale), 8, 13);
        TechNameLabel.Stylesheet = GetTitleStylesheet(titleFontSize);

        var metaFontSize = Math.Clamp((int) MathF.Round(8.5f * scale), 7, 11);
        var metaFont = _resCache.GetFont("/Fonts/NotoSans/NotoSans-Regular.ttf", metaFontSize);
        CostLabel.FontOverride = metaFont;
        TierLabel.FontOverride = metaFont;
    }

    private Stylesheet GetTitleStylesheet(int fontSize)
    {
        if (TitleStylesheetCache.TryGetValue(fontSize, out var cached))
            return cached;

        var font = _resCache.GetFont("/Fonts/NotoSans/NotoSans-Regular.ttf", fontSize);
        var sheet = new Stylesheet([
            new StyleRule(
                new SelectorElement(typeof(RichTextLabel), null, null, null),
                [
                    new StyleProperty(Label.StylePropertyFont, font),
                    new StyleProperty(nameof(RichTextLabel.LineHeightScale), 0.9f),
                ])
        ]);

        TitleStylesheetCache[fontSize] = sheet;
        return sheet;
    }
    // Erida end
}

public sealed class DrawButton : Button
{
    public event Action? OnDrawModeChanged;

    public DrawButton()
    {
    }

    protected override void DrawModeChanged()
    {
        OnDrawModeChanged?.Invoke();
    }
}
