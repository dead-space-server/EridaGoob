using System.Numerics;
using Content.Client._Erida.Stylesheets;
using Content.Client._Erida.UserInterface.Controls;
using Content.Client._Erida.UserInterface.Shapes;
using Content.Client.Options.UI;
using Content.Shared._Erida.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;

namespace Content.Client._Erida.Options;

[GenerateTypedNameReferences]
public sealed partial class EridaThemeOptions : Control
{
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private EridaThemeManager _theme = default!;

    private const float SwatchSize = 26f;
    private const float PreviewSize = 20f;
    private const int PreviewCount = 6;

    /// <summary>
    /// The first one is the default.
    /// </summary>
    private static readonly string[] Presets =
    [
        ECCVars.InterfaceAccent.DefaultValue,
        "#6750A4",
        "#A0457A",
        "#B3261E",
        "#C26A00",
        "#3A7D44",
        "#00838F",
        "#6E7781",
    ];

    private readonly List<(string Hex, ShapedPanel Swatch)> _swatches = [];
    private readonly List<ShapedPanel> _previews = [];
    private readonly Dictionary<string, EridaPalette> _palettes = [];

    private string _accent = ECCVars.InterfaceAccent.DefaultValue;

    private event Action? AccentEdited;

    public EridaThemeOptions()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        foreach (var hex in Presets)
        {
            AddSwatch(hex);
        }

        for (var i = 0; i < PreviewCount; i++)
        {
            var preview = new ShapedPanel
            {
                Shape = ShapeStyle.Rounded(4f),
                SetSize = new Vector2(PreviewSize, PreviewSize),
                BorderThickness = 1f,
            };

            _previews.Add(preview);
            Preview.AddChild(preview);
        }

        HexEdit.OnTextChanged += args =>
        {
            var valid = EridaThemeManager.TryParseSeed(args.Text, out var color);
            HexEdit.ModulateSelfOverride = valid || args.Text.Length == 0 ? null : _theme.Palette.Error;

            if (!valid)
                return;

            SetAccent(EridaThemeManager.FormatSeed(color), updateText: false);
            AccentEdited?.Invoke();
        };

        HexEdit.OnFocusExit += _ =>
        {
            HexEdit.Text = _accent;
            HexEdit.ModulateSelfOverride = null;
        };
    }

    public void AddOptions(OptionsTabControlRow row)
    {
        row.AddOption(new AccentOption(row, _cfg, this));
        row.AddOptionCheckBox(ECCVars.InterfaceTransparency, TransparencyCheckBox);
        row.AddOptionPercentSlider(ECCVars.InterfaceTransparencyAmount, TransparencySlider, max: 0.5f);
        row.AddOptionCheckBox(ECCVars.LobbyChatLeft, ChatLeftCheckBox);
    }

    private void AddSwatch(string hex)
    {
        var swatch = new ShapedPanel
        {
            Shape = ShapeStyle.Pill,
            SetSize = new Vector2(SwatchSize, SwatchSize),
            BorderThickness = 2f,
        };

        var button = new ContainerButton { ToolTip = hex };
        button.AddChild(swatch);
        button.OnPressed += _ =>
        {
            SetAccent(hex, updateText: true);
            AccentEdited?.Invoke();
        };

        _swatches.Add((hex, swatch));
        Swatches.AddChild(button);
    }

    private void SetAccent(string hex, bool updateText)
    {
        _accent = EridaThemeManager.FormatSeed(EridaThemeManager.ParseSeed(hex));

        if (updateText)
            HexEdit.Text = _accent;

        UpdateColors();
    }

    private void UpdateColors()
    {
        foreach (var (hex, swatch) in _swatches)
        {
            var palette = GetPalette(hex);
            // Show the generated color, not the raw seed.
            swatch.BackgroundColor = palette.Primary;
            swatch.BorderColor = hex == _accent ? palette.OnSurface : Color.Transparent;
        }

        var current = GetPalette(_accent);
        Color[] colors =
        [
            current.Layer0Base,
            current.SurfaceContainerLow,
            current.SecondaryContainer,
            current.PrimaryContainer,
            current.Primary,
            current.Tertiary,
        ];

        for (var i = 0; i < PreviewCount; i++)
        {
            _previews[i].BackgroundColor = colors[i];
            _previews[i].BorderColor = current.OutlineVariant;
        }
    }

    private EridaPalette GetPalette(string hex)
    {
        if (!_palettes.TryGetValue(hex, out var palette))
        {
            palette = EridaPalette.Generate(Color.FromHex(hex), dark: true);
            _palettes[hex] = palette;
        }

        return palette;
    }

    private sealed class AccentOption : BaseOptionCVar<string>
    {
        private readonly EridaThemeOptions _owner;

        protected override string Value
        {
            get => _owner._accent;
            set => _owner.SetAccent(value, updateText: true);
        }

        public AccentOption(OptionsTabControlRow row, IConfigurationManager cfg, EridaThemeOptions owner)
            : base(row, cfg, ECCVars.InterfaceAccent)
        {
            _owner = owner;
            owner.AccentEdited += ValueChanged;
        }

        protected override bool IsValueEqual(string a, string b)
        {
            return string.Equals(a, b, StringComparison.OrdinalIgnoreCase);
        }
    }
}
