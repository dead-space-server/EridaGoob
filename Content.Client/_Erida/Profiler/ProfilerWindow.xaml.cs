using System.Linq;
using System.Text;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared._Erida.Profiler;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Erida.Profiler;

[GenerateTypedNameReferences]
public sealed partial class ProfilerWindow : FancyWindow
{
    [Dependency] private IClipboardManager _clipboard = default!;

    private const int MaxSlowTicks = 50;
    private const int ReportSystems = 20;
    private const int ReportSlowTicks = 5;
    private const int ReportSlowTickNodes = 40;
    private const int ReportLogs = 20;
    private const float HeavyShare = 0.25f;
    private const float NoticeableShare = 0.05f;
    private static readonly Color HeavyColor = Color.FromHex("#E8584F");
    private static readonly Color NoticeableColor = Color.FromHex("#E8C04F");
    private static readonly HashSet<string> ContainerGroups = ["Frame", "Ticks", "Tick", "Systems"];

    private ProfilerOverview? _overview;
    private List<ProfilerSystemStat> _systems = [];
    private readonly List<ProfilerSystemStat> _sortedSystems = [];
    private readonly List<Label[]> _systemRows = [];
    private readonly List<ProfilerSlowTick> _slowTicks = [];
    private readonly Dictionary<string, LogEntry> _logs = [];
    private readonly List<LogEntry> _logOrder = [];
    private SystemSort _sort = SystemSort.Total;
    private ProfilerSlowTick? _selectedTick;

    public event Action? ResetPressed;

    public ProfilerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Tabs.SetTabTitle(0, Loc.GetString("erida-profiler-tab-systems"));
        Tabs.SetTabTitle(1, Loc.GetString("erida-profiler-tab-slow-ticks"));
        Tabs.SetTabTitle(2, Loc.GetString("erida-profiler-tab-logs"));

        SortName.OnPressed += _ => SetSort(SystemSort.Name);
        SortTotal.OnPressed += _ => SetSort(SystemSort.Total);
        SortAvg.OnPressed += _ => SetSort(SystemSort.Avg);
        SortMax.OnPressed += _ => SetSort(SystemSort.Max);
        SortAlloc.OnPressed += _ => SetSort(SystemSort.Alloc);
        SortCalls.OnPressed += _ => SetSort(SystemSort.Calls);

        CopyButton.OnPressed += _ => _clipboard.SetText(BuildReport());
        ResetButton.OnPressed += _ => ResetPressed?.Invoke();

        // Restoring the selection after a rebuild fires this too, so the shown tick must not be redrawn.
        SlowTickList.OnItemSelected += args =>
        {
            if (args.ItemList[args.ItemIndex].Metadata is ProfilerSlowTick tick && !IsSameTick(_selectedTick, tick))
                ShowSlowTick(tick);
        };

        ShowWarnings.OnToggled += _ => RefreshLogVisibility();
        ShowErrors.OnToggled += _ => RefreshLogVisibility();
        ShowFatal.OnToggled += _ => RefreshLogVisibility();

        RebuildOverview();
    }

    #region Data

    public void SetState(ProfilerEuiState state)
    {
        _overview = state.Overview;
        _systems = state.Systems;

        _slowTicks.Clear();
        _slowTicks.AddRange(state.SlowTicks);
        _selectedTick = null;

        LogList.RemoveAllChildren();
        _logs.Clear();

        StatusLabel.Visible = !state.Enabled;
        StatusLabel.Text = Loc.GetString("erida-profiler-disabled");
        ThresholdLabel.Text = Loc.GetString("erida-profiler-slow-ticks-threshold",
            ("ms", state.SlowTickMs.ToString("F0")));

        RebuildOverview();
        RebuildSystems();
        RebuildSlowTicks();
        UpdateLogs(state.Logs);
    }

    public void UpdateStats(ProfilerOverview overview, List<ProfilerSystemStat> systems)
    {
        _overview = overview;
        _systems = systems;
        RebuildOverview();
        RebuildSystems();
    }

    public void AddSlowTicks(List<ProfilerSlowTick> slowTicks)
    {
        _slowTicks.AddRange(slowTicks);
        if (_slowTicks.Count > MaxSlowTicks)
            _slowTicks.RemoveRange(0, _slowTicks.Count - MaxSlowTicks);

        RebuildSlowTicks();
    }

    /// <summary>
    /// Updates existing log entries in place and adds new ones.
    /// </summary>
    public void UpdateLogs(List<ProfilerLogGroup> logs)
    {
        foreach (var log in logs)
        {
            if (_logs.TryGetValue(log.Key, out var entry))
            {
                UpdateLogEntry(entry, log);
                continue;
            }

            entry = CreateLogEntry(log);
            _logs[log.Key] = entry;
            LogList.AddChild(entry.Box);
        }

        SortLogs();
        RefreshLogVisibility();
    }

    #endregion

    #region Overview

    private void RebuildOverview()
    {
        if (_overview is not { } o)
        {
            OverviewLabel.Text = Loc.GetString("erida-profiler-overview-waiting");
            return;
        }

        OverviewLabel.Text = FormatOverview(o);
    }

    private static string FormatOverview(ProfilerOverview o)
    {
        return Loc.GetString("erida-profiler-overview",
            ("seconds", o.WindowSeconds.ToString("F0")),
            ("ticks", o.Ticks),
            ("avg", o.AvgTickMs.ToString("F1")),
            ("max", o.MaxTickMs.ToString("F1")),
            ("slow", o.SlowTicks),
            ("gc", o.GcPauseMs.ToString("F0")),
            ("gen0", o.Gen0),
            ("gen1", o.Gen1),
            ("gen2", o.Gen2),
            ("memory", FormatBytes(o.ManagedMemory)),
            ("entities", o.Entities),
            ("players", o.Players));
    }

    #endregion

    #region Systems

    private void SetSort(SystemSort sort)
    {
        _sort = sort;
        RebuildSystems();
    }

    /// <summary>
    /// Rewrites the rows in place, adding or removing only the difference in row count.
    /// </summary>
    private void RebuildSystems()
    {
        _sortedSystems.Clear();
        _sortedSystems.AddRange(_systems);
        _sortedSystems.Sort(GetComparison(_sort));

        while (_systemRows.Count > _sortedSystems.Count)
        {
            foreach (var label in _systemRows[^1])
            {
                SystemsGrid.RemoveChild(label);
            }

            _systemRows.RemoveAt(_systemRows.Count - 1);
        }

        for (var i = 0; i < _sortedSystems.Count; i++)
        {
            if (i >= _systemRows.Count)
                _systemRows.Add(CreateSystemRow());

            var stat = _sortedSystems[i];
            var row = _systemRows[i];
            row[0].Text = stat.Name;
            row[1].Text = stat.TotalMs.ToString("F2");
            row[2].Text = stat.AvgMs.ToString("F3");
            row[3].Text = stat.MaxMs.ToString("F2");
            row[4].Text = FormatBytes(stat.AvgAlloc);
            row[5].Text = stat.Calls.ToString();
        }
    }

    private Label[] CreateSystemRow()
    {
        Label[] row =
        [
            new Label { ClipText = true, HorizontalExpand = true },
            NumberLabel(),
            NumberLabel(),
            NumberLabel(),
            NumberLabel(),
            NumberLabel(),
        ];

        foreach (var label in row)
        {
            SystemsGrid.AddChild(label);
        }

        return row;
    }

    private static Comparison<ProfilerSystemStat> GetComparison(SystemSort sort)
    {
        return sort switch
        {
            SystemSort.Name => static (a, b) => string.CompareOrdinal(a.Name, b.Name),
            SystemSort.Avg => static (a, b) => b.AvgMs.CompareTo(a.AvgMs),
            SystemSort.Max => static (a, b) => b.MaxMs.CompareTo(a.MaxMs),
            SystemSort.Alloc => static (a, b) => b.AvgAlloc.CompareTo(a.AvgAlloc),
            SystemSort.Calls => static (a, b) => b.Calls.CompareTo(a.Calls),
            _ => static (a, b) => b.TotalMs.CompareTo(a.TotalMs),
        };
    }

    private static Label NumberLabel()
    {
        return new Label { Align = Label.AlignMode.Right, Margin = new Thickness(8, 0, 4, 0) };
    }

    #endregion

    #region Slow ticks

    private void RebuildSlowTicks()
    {
        SlowTickList.Clear();

        for (var i = _slowTicks.Count - 1; i >= 0; i--)
        {
            var tick = _slowTicks[i];
            var item = SlowTickList.AddItem(Loc.GetString("erida-profiler-slow-tick-item",
                ("time", tick.Time.ToLocalTime().ToString("HH:mm:ss")),
                ("tick", tick.Tick.ToString()),
                ("ms", tick.FrameMs.ToString("F0"))));
            item.Metadata = tick;

            if (IsSameTick(_selectedTick, tick))
                item.Selected = true;
        }

        if (_selectedTick == null)
            ShowSlowTick(null);
    }

    private static bool IsSameTick(ProfilerSlowTick? a, ProfilerSlowTick b)
    {
        return a is { } tick && tick.Time == b.Time && tick.Tick == b.Tick;
    }

    private void ShowSlowTick(ProfilerSlowTick? slowTick)
    {
        _selectedTick = slowTick;
        SlowTickNodes.RemoveAllChildren();

        if (slowTick is not { } tick)
        {
            SlowTickSummary.Text = Loc.GetString(_slowTicks.Count == 0
                ? "erida-profiler-slow-ticks-empty"
                : "erida-profiler-slow-ticks-select");
            return;
        }

        SlowTickSummary.Text = FormatSlowTickSummary(tick);

        foreach (var node in tick.Nodes)
        {
            var label = new Label
            {
                Text = FormatNode(node),
                ClipText = true,
                Margin = new Thickness(node.Depth * 16, 0, 0, 0),
            };

            // Highlight the entries that ate a large share of the frame, skipping groups that only wrap others.
            if (!node.IsGroup || !ContainerGroups.Contains(node.Name))
            {
                var share = tick.FrameMs > 0f ? node.TimeMs / tick.FrameMs : 0f;
                if (share >= HeavyShare)
                    label.FontColorOverride = HeavyColor;
                else if (share >= NoticeableShare)
                    label.FontColorOverride = NoticeableColor;
            }

            SlowTickNodes.AddChild(label);
        }
    }

    private static string FormatSlowTickSummary(ProfilerSlowTick tick)
    {
        var summary = Loc.GetString("erida-profiler-slow-tick-summary",
            ("time", tick.Time.ToLocalTime().ToString("HH:mm:ss")),
            ("tick", tick.Tick.ToString()),
            ("ms", tick.FrameMs.ToString("F0")),
            ("ticks", tick.TickCount),
            ("gc", tick.GcPauseMs.ToString("F0")));

        if (tick.Truncated)
            summary += " " + Loc.GetString("erida-profiler-slow-tick-truncated");

        return summary;
    }

    private static string FormatNode(ProfilerNode node)
    {
        if (node.Value is { } value)
            return $"{node.Name}: {value}";

        if (node.TimeMs <= 0f && node.Alloc == 0)
            return node.Name;

        return Loc.GetString("erida-profiler-node",
            ("name", node.Name),
            ("ms", node.TimeMs.ToString("F2")),
            ("alloc", FormatBytes(node.Alloc)));
    }

    #endregion

    #region Logs

    /// <summary>
    /// Puts the most recently seen groups first, moving only the entries that changed place.
    /// </summary>
    private void SortLogs()
    {
        _logOrder.Clear();
        _logOrder.AddRange(_logs.Values);
        _logOrder.Sort(static (a, b) => b.Log.LastSeen.CompareTo(a.Log.LastSeen));

        for (var i = 0; i < _logOrder.Count; i++)
        {
            var box = _logOrder[i].Box;
            if (box.GetPositionInParent() != i)
                box.SetPositionInParent(i);
        }
    }

    private void RefreshLogVisibility()
    {
        var any = false;
        foreach (var entry in _logs.Values)
        {
            var shown = IsLevelShown(entry.Log);
            entry.Box.Visible = shown;
            any |= shown;
        }

        LogsEmptyLabel.Visible = !any;
    }

    private bool IsLevelShown(ProfilerLogGroup log)
    {
        return log.Level switch
        {
            LogLevel.Fatal => ShowFatal.Pressed,
            LogLevel.Error => ShowErrors.Pressed,
            _ => ShowWarnings.Pressed,
        };
    }

    private static LogEntry CreateLogEntry(ProfilerLogGroup log)
    {
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical };
        var header = new Button
        {
            Text = FormatLogHeader(log),
            ToggleMode = true,
            ClipText = true,
            HorizontalExpand = true,
            TextAlign = Label.AlignMode.Left,
        };

        if (log.Level != LogLevel.Warning)
            header.AddStyleClass(StyleNano.ButtonCaution);

        box.AddChild(header);

        var entry = new LogEntry(log, box, header);
        header.OnToggled += args => SetLogExpanded(entry, args.Pressed);
        return entry;
    }

    private static void UpdateLogEntry(LogEntry entry, ProfilerLogGroup log)
    {
        entry.Log = log;
        entry.Header.Text = FormatLogHeader(log);

        if (entry.Details == null)
            return;

        if (entry.Header.Pressed)
        {
            entry.Details.SetMessage(FormattedMessage.FromUnformatted(FormatLogDetails(log)));
            return;
        }

        // A collapsed entry drops its stale details and builds them again on the next expand.
        entry.Box.RemoveChild(entry.Details);
        entry.Details = null;
    }

    /// <summary>
    /// Details hold up to several kilobytes of stack trace, so they are only built when the entry is opened.
    /// </summary>
    private static void SetLogExpanded(LogEntry entry, bool expanded)
    {
        if (expanded && entry.Details == null)
        {
            entry.Details = new RichTextLabel { Margin = new Thickness(8, 2, 4, 6) };
            entry.Details.SetMessage(FormattedMessage.FromUnformatted(FormatLogDetails(entry.Log)));
            entry.Box.AddChild(entry.Details);
        }

        if (entry.Details != null)
            entry.Details.Visible = expanded;
    }

    private static string FormatLogHeader(ProfilerLogGroup log)
    {
        var firstLine = log.Message;
        var newLine = firstLine.IndexOf('\n');
        if (newLine >= 0)
            firstLine = firstLine[..newLine];

        return $"[{FormatLevel(log.Level)}] ×{log.Count} {log.Sawmill}: {firstLine}";
    }

    private static string FormatLogDetails(ProfilerLogGroup log)
    {
        var builder = new StringBuilder();
        builder.AppendLine(Loc.GetString("erida-profiler-log-seen",
            ("first", log.FirstSeen.ToLocalTime().ToString("HH:mm:ss")),
            ("last", log.LastSeen.ToLocalTime().ToString("HH:mm:ss")),
            ("count", log.Count)));
        builder.AppendLine(log.Message);

        if (log.Exception != null)
            builder.AppendLine(log.Exception);

        return builder.ToString().TrimEnd();
    }

    private static string FormatLevel(LogLevel level)
    {
        return level switch
        {
            LogLevel.Fatal => "FTL",
            LogLevel.Error => "ERR",
            _ => "WRN",
        };
    }

    #endregion

    #region Report

    private string BuildReport()
    {
        var builder = new StringBuilder();
        builder.AppendLine($"== {Loc.GetString("erida-profiler-window-title")} {DateTime.Now:yyyy-MM-dd HH:mm:ss} ==");

        if (_overview is { } overview)
            builder.AppendLine(FormatOverview(overview));

        builder.AppendLine();
        builder.AppendLine($"-- {Loc.GetString("erida-profiler-tab-systems")} --");
        foreach (var stat in _systems.Take(ReportSystems))
        {
            builder.AppendLine(
                $"{stat.Name}: total {stat.TotalMs:F2}ms, avg {stat.AvgMs:F3}ms, max {stat.MaxMs:F2}ms, alloc {FormatBytes(stat.AvgAlloc)}, calls {stat.Calls}");
        }

        builder.AppendLine();
        builder.AppendLine($"-- {Loc.GetString("erida-profiler-tab-slow-ticks")} --");
        for (var i = _slowTicks.Count - 1; i >= Math.Max(0, _slowTicks.Count - ReportSlowTicks); i--)
        {
            var tick = _slowTicks[i];
            builder.AppendLine(FormatSlowTickSummary(tick));
            foreach (var node in tick.Nodes.Take(ReportSlowTickNodes))
            {
                builder.Append(' ', node.Depth * 2).AppendLine(FormatNode(node));
            }

            builder.AppendLine();
        }

        builder.AppendLine($"-- {Loc.GetString("erida-profiler-tab-logs")} --");
        foreach (var log in _logs.Values.Select(e => e.Log).OrderByDescending(l => l.Count).Take(ReportLogs))
        {
            builder.AppendLine(FormatLogHeader(log));
            if (log.Exception != null)
                builder.AppendLine(log.Exception);
        }

        return builder.ToString();
    }

    #endregion

    private static string FormatBytes(long bytes)
    {
        return bytes switch
        {
            >= 1L << 30 => $"{bytes / (double) (1L << 30):F2} GB",
            >= 1L << 20 => $"{bytes / (double) (1L << 20):F1} MB",
            >= 1L << 10 => $"{bytes / (double) (1L << 10):F1} KB",
            _ => $"{bytes} B",
        };
    }

    private sealed class LogEntry(ProfilerLogGroup log, BoxContainer box, Button header)
    {
        public ProfilerLogGroup Log = log;
        public readonly BoxContainer Box = box;
        public readonly Button Header = header;
        public RichTextLabel? Details;
    }

    private enum SystemSort : byte
    {
        Name,
        Total,
        Avg,
        Max,
        Alloc,
        Calls,
    }
}
