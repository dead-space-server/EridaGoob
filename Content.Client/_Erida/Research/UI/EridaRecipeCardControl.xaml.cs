using Content.Client.Lathe;
using Content.Shared.Research.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._Erida.Research.UI;

[GenerateTypedNameReferences]
public sealed partial class EridaRecipeCardControl : PanelContainer
{
    public EridaRecipeCardControl(
        TechnologyPrototype technology,
        LatheRecipePrototype proto,
        IPrototypeManager prototypeManager,
        SpriteSystem sprite,
        LatheSystem lathe)
    {
        RobustXamlLoader.Load(this);

        var discipline = prototypeManager.Index(technology.Discipline);
        if (PanelOverride is StyleBoxFlat accentBox)
            accentBox.BorderColor = discipline.Color;

        var msg = new FormattedMessage();
        msg.PushColor(ResearchUiPalette.TextPrimary);
        msg.AddText(lathe.GetRecipeName(proto));
        msg.Pop();
        NameLabel.SetMessage(msg);

        if (proto.Result.HasValue)
            Showcase.Texture = sprite.Frame0(prototypeManager.Index(proto.Result.Value));

        if (proto.Description.HasValue)
        {
            var tooltip = new Tooltip();
            tooltip.SetMessage(FormattedMessage.FromUnformatted(lathe.GetRecipeDescription(proto)));
            Main.TooltipSupplier = _ => tooltip;
        }
    }
}
