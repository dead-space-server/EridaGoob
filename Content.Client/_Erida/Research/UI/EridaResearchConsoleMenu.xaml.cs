[GenerateTypedNameReferences]
public sealed partial class EridaResearchConsoleMenu : FancyWindow
{
    public Action<string>? OnTechnologyCardPressed;
    public Action? OnServerButtonPressed;

    [Dependency] private readonly IEntityManager _entity = default!;
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    [Dependency] private readonly IPlayerManager _player = default!;

    private readonly ResearchSystem _research;
    private readonly SpriteSystem _sprite;
    private readonly AccessReaderSystem _accessReader;
    private readonly LatheSystem _lathe;

    public EntityUid Entity;
    public ProtoId<TechnologyPrototype>? CurrentTech;
    public Dictionary<string, ResearchAvailability> List = new();
    public int Points;

    private ProtoId<TechDisciplinePrototype>? _selectedDiscipline;
    private readonly Dictionary<string, Vector2> _layoutPositions = new();
    private readonly Dictionary<string, EridaResearchConsoleItem> _items = new();

    private bool _dragging;
    private Vector2 _position = new(24, 24);
    private float _zoom = 0.7f;
    private const float MinZoom = 0.6f;
    private const float MaxZoom = 1.25f;
    private const float ZoomSpeed = 0.08f;

    private const float ColumnSpacing = 276f;
    private const float RowGap = 12f;
    private const float LanePadTop = 14f;
    private const float LanePadBottom = 14f;
    private const float LaneGap = 14f;

    public EridaResearchConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _research = _entity.System<ResearchSystem>();
        _sprite = _entity.System<SpriteSystem>();
        _accessReader = _entity.System<AccessReaderSystem>();
        _lathe = _entity.System<LatheSystem>();

        ServerButton.OnPressed += _ => OnServerButtonPressed?.Invoke();
        SearchBar.OnTextChanged += _ => ApplySearchFilter();
        DragContainer.OnKeyBindDown += OnKeybindDown;
        DragContainer.OnKeyBindUp += OnKeybindUp;
        RecenterButton.OnPressed += _ => Recenter();

        ShowEmptyInfoPanel();
        UpdatePanels(List);
        Recenter();
    }

    public void SetEntity(EntityUid entity)
        => Entity = entity;

    public void UpdatePanels(Dictionary<string, ResearchAvailability> dict)
    {
        List = dict;
        RebuildTree();
        UpdateDisciplineTabs();

        if (CurrentTech.HasValue && List.TryGetValue(CurrentTech.Value, out var availability))
        {
            var proto = _prototype.Index<TechnologyPrototype>(CurrentTech.Value);
            SelectTech(proto, availability);
        }
        else
        {
            ShowEmptyInfoPanel();
        }
    }

    public void UpdateInformationPanel(int points)
    {
        Points = points;
        ResearchAmountLabel.Text = Loc.GetString("erida-research-console-tech-cost-label", ("cost", points));
        UpdateDisciplineTabs();
    }

    private void UpdateDisciplineTabs()
    {
        TierDisplayContainer.RemoveAllChildren();

        TierDisplayContainer.AddChild(CreateDisciplineTabButton(
            null,
            Loc.GetString("erida-research-console-all-disciplines"),
            null,
            null,
            ResearchUiPalette.HeaderAccent,
            _selectedDiscipline == null));

        if (!_entity.TryGetComponent(Entity, out TechnologyDatabaseComponent? database))
            return;

        foreach (var disciplineId in database.SupportedDisciplines)
        {
            var discipline = _prototype.Index<TechDisciplinePrototype>(disciplineId);
            var tier = _research.GetTierCompletionPercentage(database, discipline, _prototype);
            var shortKey = $"erida-research-console-discipline-short-{discipline.ID.ToLowerInvariant()}";
            var shortName = Loc.TryGetString(shortKey, out var locShort)
                ? locShort
                : (string.IsNullOrEmpty(discipline.UiName) ? Loc.GetString(discipline.Name) : discipline.UiName);
            var text = $"{shortName} · {Loc.GetString("erida-research-console-tier-percentage", ("perc", tier))}";

            TierDisplayContainer.AddChild(CreateDisciplineTabButton(
                disciplineId,
                text,
                Loc.GetString(discipline.Name),
                _sprite.Frame0(discipline.Icon),
                discipline.Color,
                _selectedDiscipline == disciplineId));
        }
    }

    private Control CreateDisciplineTabButton(
        ProtoId<TechDisciplinePrototype>? disciplineId,
        string labelText,
        string? tooltip,
        Texture? icon,
        Color accentColor,
        bool isActive)
    {
        var accentPanel = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat
            {
                BorderThickness = new Thickness(3, 0, 0, 0),
                BorderColor = isActive ? accentColor : accentColor.WithAlpha(0.3f)
            }
        };

        var innerPanel = new PanelContainer
        {
            Margin = new Thickness(2, 0, 0, 0),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = isActive ? ResearchUiPalette.CardBackground : ResearchUiPalette.PanelBackground,
                BorderColor = isActive ? ResearchUiPalette.SelectedBorder.WithAlpha(0.6f) : ResearchUiPalette.CardBorder,
                BorderThickness = new Thickness(1)
            }
        };

        var btn = new Button
        {
            ModulateSelfOverride = Color.Transparent,
            HorizontalExpand = true,
            VerticalExpand = true,
            MinHeight = 32,
            ToolTip = tooltip
        };
        btn.OnPressed += _ =>
        {
            if (_selectedDiscipline == disciplineId)
                return;

            _selectedDiscipline = disciplineId;
            RebuildTree();
            UpdateDisciplineTabs();
            Recenter();
        };

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Margin = new Thickness(10, 4),
            SeparationOverride = 6,
            VerticalAlignment = VAlignment.Center,
            MouseFilter = MouseFilterMode.Ignore
        };

        if (icon != null)
        {
            row.AddChild(new TextureRect
            {
                Texture = icon,
                SetSize = new Vector2(16, 16),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                VerticalAlignment = VAlignment.Center,
                MouseFilter = MouseFilterMode.Ignore
            });
        }

        row.AddChild(new Label
        {
            Text = labelText,
            FontColorOverride = isActive ? ResearchUiPalette.TextPrimary : ResearchUiPalette.TextSecondary,
            VerticalAlignment = VAlignment.Center,
            MouseFilter = MouseFilterMode.Ignore
        });

        innerPanel.AddChild(btn);
        innerPanel.AddChild(row);
        accentPanel.AddChild(innerPanel);
        return accentPanel;
    }

    private void RebuildTree()
    {
        DragContainer.RemoveAllChildren();
        _items.Clear();

        foreach (var (id, availability) in List)
        {
            var proto = _prototype.Index<TechnologyPrototype>(id);
            if (_selectedDiscipline.HasValue && proto.Discipline != _selectedDiscipline.Value)
                continue;

            var control = new EridaResearchConsoleItem(proto, _sprite, availability);
            control.SetSelected(CurrentTech == id);
            control.SelectAction += SelectTech;

            DragContainer.AddChild(control);
            _items[id] = control;
        }

        RelayoutTree();
        ApplySearchFilter();
    }

    private void RelayoutTree()
    {
        DragContainer.Swimlanes.Clear();
        _layoutPositions.Clear();

        foreach (var item in _items.Values)
        {
            item.SetScale(_zoom);
            item.Measure(new Vector2(float.PositiveInfinity, float.PositiveInfinity));
        }

        var visibleProtos = _items.Values.Select(i => i.Prototype).ToList();

        if (_selectedDiscipline.HasValue)
        {
            var laneBottom = LayoutDisciplineGroup(visibleProtos, LanePadTop * _zoom);
            var discProto = _prototype.Index<TechDisciplinePrototype>(_selectedDiscipline.Value);
            DragContainer.Swimlanes.Add((discProto.Color, 0f, laneBottom));
        }
        else
        {
            var disciplines = GetOrderedDisciplines(visibleProtos);
            var currentY = 0f;

            foreach (var discId in disciplines)
            {
                var group = visibleProtos.Where(t => t.Discipline == discId).ToList();
                if (group.Count == 0)
                    continue;

                var laneTop = currentY;
                var laneBottom = LayoutDisciplineGroup(group, currentY + LanePadTop * _zoom);
                var discProto = _prototype.Index<TechDisciplinePrototype>(discId);
                DragContainer.Swimlanes.Add((discProto.Color, laneTop, laneBottom));

                currentY = laneBottom + LaneGap * _zoom;
            }
        }

        ApplyPositions();
    }

    private List<ProtoId<TechDisciplinePrototype>> GetOrderedDisciplines(List<TechnologyPrototype> allProtos)
    {
        if (_entity.TryGetComponent(Entity, out TechnologyDatabaseComponent? database) &&
            database.SupportedDisciplines.Count > 0)
        {
            return database.SupportedDisciplines.ToList();
        }

        return allProtos.Select(t => t.Discipline).Distinct().ToList();
    }

    // Place techs left-to-right by prerequisite depth and stack cards vertically using measured heights.
    private float LayoutDisciplineGroup(List<TechnologyPrototype> techs, float startY)
    {
        if (techs.Count == 0)
            return startY;

        var techById = techs.ToDictionary(t => t.ID);
        var columns = new Dictionary<string, int>(techs.Count);
        var visiting = new HashSet<string>();

        int GetColumn(TechnologyPrototype tech)
        {
            if (columns.TryGetValue(tech.ID, out var cached))
                return cached;

            if (!visiting.Add(tech.ID))
                return Math.Max(0, tech.Tier - 1);

            var depth = 0;
            foreach (var prereqId in tech.TechnologyPrerequisites)
            {
                if (techById.TryGetValue(prereqId, out var prereq))
                    depth = Math.Max(depth, GetColumn(prereq) + 1);
            }

            visiting.Remove(tech.ID);
            var col = Math.Max(depth, Math.Max(0, tech.Tier - 1));
            columns[tech.ID] = col;
            return col;
        }

        foreach (var tech in techs)
            GetColumn(tech);

        var byColumn = techs
            .GroupBy(t => columns[t.ID])
            .OrderBy(g => g.Key);

        var rowOf = new Dictionary<string, int>(techs.Count);
        var maxBottomY = startY;
        var gap = RowGap * _zoom;
        var colStep = ColumnSpacing * _zoom;

        double GetAveragePrereqRow(TechnologyPrototype tech)
        {
            var sum = 0.0;
            var count = 0;
            foreach (var prereqId in tech.TechnologyPrerequisites)
            {
                if (!rowOf.TryGetValue(prereqId, out var prereqRow))
                    continue;

                sum += prereqRow;
                count++;
            }

            return count > 0 ? sum / count : double.MaxValue;
        }

        foreach (var group in byColumn)
        {
            var ordered = group
                .OrderBy(GetAveragePrereqRow)
                .ThenBy(t => t.Tier)
                .ThenBy(t => Loc.GetString(t.Name), StringComparer.Ordinal)
                .ToList();

            var y = startY;
            for (var row = 0; row < ordered.Count; row++)
            {
                var tech = ordered[row];
                rowOf[tech.ID] = row;
                _layoutPositions[tech.ID] = new Vector2(group.Key * colStep, y);

                var cardHeight = _items.TryGetValue(tech.ID, out var item)
                    ? Math.Max(EridaResearchConsoleItem.BaseHeight * _zoom, item.DesiredSize.Y)
                    : EridaResearchConsoleItem.BaseHeight * _zoom;

                y += cardHeight + gap;
            }

            if (ordered.Count > 0)
                maxBottomY = Math.Max(maxBottomY, y - gap);
        }

        return maxBottomY + LanePadBottom * _zoom;
    }

    protected override void MouseMove(GUIMouseMoveEventArgs args)
    {
        base.MouseMove(args);

        if (!_dragging)
            return;

        _position += args.Relative;
        DragContainer.PanOffset = _position;

        foreach (var child in DragContainer.Children)
        {
            LayoutContainer.SetPosition(child, child.Position + args.Relative);
        }
    }

    protected override void MouseWheel(GUIMouseWheelEventArgs args)
    {
        base.MouseWheel(args);

        var oldZoom = _zoom;
        _zoom = Math.Clamp(_zoom + (args.Delta.Y > 0 ? ZoomSpeed : -ZoomSpeed), MinZoom, MaxZoom);

        if (MathHelper.CloseTo(oldZoom, _zoom))
            return;

        // Zoom toward the cursor position inside the tree canvas.
        var mouseInCanvas = args.RelativePosition - (DragContainer.GlobalPosition - GlobalPosition);
        var worldPos = (mouseInCanvas - _position) / oldZoom;
        _position = mouseInCanvas - worldPos * _zoom;

        RelayoutTree();
        args.Handle();
    }

    private void OnKeybindDown(GUIBoundKeyEventArgs args)
    {
        if (args.Function == EngineKeyFunctions.Use)
            _dragging = true;
    }

    private void OnKeybindUp(GUIBoundKeyEventArgs args)
    {
        if (args.Function == EngineKeyFunctions.Use)
            _dragging = false;
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
        => _dragging ? DragMode.None : base.GetDragModeFor(relativeMousePos);

    public void SelectTech(TechnologyPrototype proto, ResearchAvailability availability)
    {
        InfoContainer.RemoveAllChildren();
        if (!_player.LocalEntity.HasValue)
            return;

        CurrentTech = proto.ID;

        foreach (var (id, item) in _items)
            item.SetSelected(id == proto.ID);

        var control = new EridaTechnologyInfoPanel(
            proto,
            _accessReader.IsAllowed(_player.LocalEntity.Value, Entity),
            availability,
            _sprite,
            List);

        control.BuyAction += args => OnTechnologyCardPressed?.Invoke(args.ID);
        control.SelectPrerequisiteAction += FocusTechnology;
        InfoContainer.AddChild(control);
    }

    private void FocusTechnology(TechnologyPrototype target)
    {
        if (!List.TryGetValue(target.ID, out var availability))
            return;

        if (_selectedDiscipline.HasValue && _selectedDiscipline.Value != target.Discipline)
        {
            _selectedDiscipline = target.Discipline;
            RebuildTree();
            UpdateDisciplineTabs();
        }

        SelectTech(target, availability);

        if (_layoutPositions.TryGetValue(target.ID, out var layoutPos))
        {
            var center = DragContainer.Size * 0.5f;
            var cardSize = _items.TryGetValue(target.ID, out var item)
                ? item.DesiredSize
                : new Vector2(EridaResearchConsoleItem.BaseWidth * _zoom, EridaResearchConsoleItem.BaseHeight * _zoom);
            _position = center - (layoutPos + cardSize * 0.5f);
            ApplyPositions();
        }
    }

    private void ShowEmptyInfoPanel()
    {
        InfoContainer.RemoveAllChildren();

        var wrapper = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            VerticalExpand = true,
            VerticalAlignment = VAlignment.Center,
            Margin = new Thickness(24)
        };

        var msg = new FormattedMessage();
        msg.PushColor(ResearchUiPalette.TextSecondary);
        msg.AddText(Loc.GetString("erida-research-console-select-prompt"));
        msg.Pop();

        var prompt = new RichTextLabel
        {
            HorizontalExpand = true,
            HorizontalAlignment = HAlignment.Center
        };
        prompt.SetMessage(msg);

        wrapper.AddChild(prompt);
        InfoContainer.AddChild(wrapper);
    }

    public void Recenter()
    {
        _position = new Vector2(24, 24);
        ApplyPositions();
    }

    private void ApplyPositions()
    {
        DragContainer.PanOffset = _position;
        DragContainer.Zoom = _zoom;

        foreach (var (id, item) in _items)
        {
            if (_layoutPositions.TryGetValue(id, out var layoutPos))
                LayoutContainer.SetPosition(item, _position + layoutPos);
        }
    }

    private void ApplySearchFilter()
    {
        var query = SearchBar.Text.Trim();
        if (string.IsNullOrEmpty(query))
        {
            foreach (var item in _items.Values)
                item.SetSearchState(false, false, false);
            return;
        }

        var directMatches = new HashSet<string>();
        foreach (var (id, item) in _items)
        {
            if (MatchesSearch(item.Prototype, query))
                directMatches.Add(id);
        }

        // Keep the full prerequisite chain visible up to matched techs in the active tab.
        var chainSet = new HashSet<string>(directMatches);
        var queue = new Queue<string>(directMatches);
        while (queue.Count > 0)
        {
            var currentId = queue.Dequeue();
            if (!_items.TryGetValue(currentId, out var currentItem))
                continue;

            foreach (var prereqId in currentItem.Prototype.TechnologyPrerequisites)
            {
                if (_items.ContainsKey(prereqId) && chainSet.Add(prereqId))
                    queue.Enqueue(prereqId);
            }
        }

        foreach (var (id, item) in _items)
        {
            item.SetSearchState(directMatches.Contains(id), chainSet.Contains(id), true);
        }
    }

    private bool MatchesSearch(TechnologyPrototype proto, string query)
    {
        if (Loc.GetString(proto.Name).Contains(query, StringComparison.OrdinalIgnoreCase) ||
            proto.ID.Contains(query, StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        foreach (var recipeId in proto.RecipeUnlocks)
        {
            if (!_prototype.TryIndex(recipeId, out var recipe))
                continue;

            if (_lathe.GetRecipeName(recipe).Contains(query, StringComparison.OrdinalIgnoreCase) ||
                recipe.ID.Contains(query, StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        return false;
    }

    public override void Close()
    {
        base.Close();

        DragContainer.RemoveAllChildren();
        InfoContainer.RemoveAllChildren();
        _items.Clear();
    }
}
